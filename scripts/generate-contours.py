"""Generate procedural terrain contour lines for the site background.

Builds a smooth random heightfield with a river valley running through it,
traces iso-lines with marching squares and writes them to src/data/contours.js
as SVG path strings in a 1600x900 viewBox.

    python3 scripts/generate-contours.py src/data/contours.js
"""
import json
import sys

import numpy as np
from scipy.ndimage import gaussian_filter
from skimage import measure
from skimage.feature import peak_local_max

SEED = 17
W, H = 240, 135
VIEW_W, VIEW_H = 1600, 900
LEVELS = 22

rng = np.random.default_rng(SEED)
field = np.zeros((H, W))
for scale, amp in [(28, 1.0), (14, 0.45), (7, 0.18)]:
    field += amp * gaussian_filter(rng.standard_normal((H, W)), scale, mode="wrap")

yy, xx = np.mgrid[0:H, 0:W]
river = np.exp(-((yy - (H * 0.78 - xx * 0.32)) ** 2) / (2 * 14**2))
field = field / np.abs(field).max() - 0.55 * river

sx, sy = VIEW_W / (W - 1), VIEW_H / (H - 1)
levels = np.linspace(field.min() + 0.05, field.max() - 0.05, LEVELS)

paths = []
for index, level in enumerate(levels):
    for contour in measure.find_contours(field, level):
        if len(contour) < 18:
            continue
        contour = measure.approximate_polygon(contour, tolerance=0.22)
        points = "L".join(f"{p[1] * sx:.0f} {p[0] * sy:.0f}" for p in contour)
        paths.append({"d": "M" + points, "l": index})

# Monitoring "stations": the most prominent summits, away from the edges.
smooth = gaussian_filter(field, 3)
peaks = peak_local_max(smooth, min_distance=10, exclude_border=10, num_peaks=5)
stations = [[round(j * sx), round(i * sy)] for i, j in peaks]

js = "// Generated by scripts/generate-contours.py. Do not edit by hand.\n"
js += f"export const contourLevels = {LEVELS};\n"
js += "export const contourPaths = " + json.dumps(paths, separators=(",", ":")) + ";\n"
js += "export const stations = " + json.dumps(stations) + ";\n"

with open(sys.argv[1], "w") as handle:
    handle.write(js)
print(f"{len(paths)} paths, {len(js) // 1024} KB, stations {stations}")
